import { readFileSync, writeFileSync } from 'node:fs';
import { describeOperations } from '../../src/testgen/contract/operations.js';

const file = new URL('../../src/testgen/adapters/cli-metadata.ts', import.meta.url);
const { errors, operations } = describeOperations();
const metadata = { errors, operations: operations.map(({ name, description }) => ({ name, description })) };
const generated = `// Generated by tools/release/codegen-testgen.ts.\nexport const commandMetadata = ${JSON.stringify(metadata, null, 2)} as const;\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== generated) {
    process.stderr.write('testgen CLI metadata is stale. Run bun tools/release/codegen-testgen.ts.\n');
    process.exitCode = 1;
  }
} else {
  writeFileSync(file, generated);
}
