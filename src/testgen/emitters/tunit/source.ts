export interface CSharpCase {
  name: string;
  body: string;
}

export function csharpFile(namespace: string, className: string, cases: CSharpCase[], members: string): string {
  const methods = cases.map(({ name, body }) => `    /// <summary>Checks the reviewed obligation for this fixture.</summary>
    /// <returns>The native assertion task.</returns>
    [Test]
    public async Task ${name}()
    {
${body}
    }`).join('\n\n');
  return `// <auto-generated/>
#nullable enable

using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Numerics;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using System.Text.RegularExpressions;
using System.Threading.Tasks;
using TUnit.Assertions;
using TUnit.Assertions.Extensions;
using TUnit.Core;

namespace ${namespace.split('.').map((part) => `@${part}`).join('.')};

/// <summary>Checks the reviewed obligation over supplied fixtures.</summary>
public sealed class @${className}
{
${methods}
${members}
}
`;
}
