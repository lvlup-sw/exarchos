/**
 * A retired action name stays retired, on every surface that publishes one.
 *
 * Removing a registered action name is a contract change, not an internal edit:
 * the name is a CLI subcommand, a tool-description advertisement, and — for a
 * view — a projection registration and a `--follow` target. Those surfaces are
 * separately maintained lists, so a retirement removes the name from four or
 * five places and a later change can put it back in one of them without
 * anything noticing. A half-present name is worse than either state: the CLI
 * advertises a subcommand whose router answers `UNKNOWN_ACTION`.
 *
 * The retired set is DATA. A future retirement adds a row and inherits every
 * surface check; a surface added later is wired in once, here, and every past
 * retirement is checked against it retroactively.
 */
import { readFileSync } from 'node:fs';
import path from 'node:path';
