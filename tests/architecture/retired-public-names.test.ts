const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

/** Where the CLI declares which view actions get a `--follow` flag. */
const CLI_MODULE = 'src/adapters/cli/cli.ts';

/**
 * The GENERATED addressing set of the compiled contract surface.
 *
 * Read as source rather than imported for the same reason as the module above,
 * and included because it is the surface that actually went stale: the compiled
 * artifacts are regenerated by a separate gesture from the declaration edit, so
 * a retirement that never re-ran it ships a client that can still address the
 * dead name.
 */
const ACTION_IDS_MODULE = 'src/contract/cli/generated/cli-action-ids.ts';

function cliActionIds(): string[] {
  const { commentMaskedSource } = lexModule(
    readFileSync(path.join(REPO_ROOT, ACTION_IDS_MODULE), 'utf8'),
    path.basename(ACTION_IDS_MODULE),
  );
  const declaration = /CLI_ACTION_IDS[^=]*=\s*\[([^\]]*)\]/.exec(commentMaskedSource);
  if (!declaration?.[1]) return [];
  return [...declaration[1].matchAll(/'([^']+)'/g)].map((match) => match[1]!);
}

