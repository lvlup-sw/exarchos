/**
 * The members of `VIEW_FOLLOW_ACTIONS`, read from the CLI module's SOURCE.
 *
 * Importing the module would be more direct, but this tier has no `bun:sqlite`
 * alias and the CLI's transitive graph reaches the SQLite backend. The set is a
 * flat literal, so lexing it is exact; `commentMaskedSource` keeps the string
 * literals and blanks the comments, so the prose above the declaration — which
 * names its members — cannot answer for the declaration.
 */
function viewFollowActions(): string[] {
  const { commentMaskedSource } = lexModule(
    readFileSync(path.join(REPO_ROOT, CLI_MODULE), 'utf8'),
    path.basename(CLI_MODULE),
  );
  const declaration = /VIEW_FOLLOW_ACTIONS[^=]*=\s*new Set\(\[([^\]]*)\]\)/.exec(commentMaskedSource);
  if (!declaration?.[1]) return [];
  return [...declaration[1].matchAll(/'([^']+)'/g)].map((match) => match[1]!);
}

/** Parse the `Actions: a, b, c` advertisement out of a tool description. */
function advertisedActions(slimDescription: string | undefined): string[] {
  const match = /Actions:\s*(.+)$/s.exec(slimDescription ?? '');
  if (!match?.[1]) return [];
  return match[1].split(',').map((entry) => entry.trim()).filter(Boolean);
}

describe('retired public names', () => {
  it('RetiredActionNames_AreRemovedFromEveryPublishedSurface', () => {
    // The denominator, five times over: an empty retired set would make the loop
    // pass by never running, and an empty surface would make each `not.toContain`
    // trivially true against a list that failed to load.
    expect(RETIRED.length, 'the retired set is empty — this guard governs nothing').toBeGreaterThan(0);
    expect(BUILTIN_VIEW_NAMES.size, 'BUILTIN_VIEW_NAMES is empty').toBeGreaterThan(10);
    const followActions = viewFollowActions();
    expect(
      followActions.length,
      `VIEW_FOLLOW_ACTIONS could not be read out of ${CLI_MODULE} — the declaration moved ` +
        'or changed shape, so the surface check below is inert',
    ).toBeGreaterThan(1);
    expect(TOOL_REGISTRY.length, 'the registry is empty').toBeGreaterThan(0);
    const actionIds = cliActionIds();
    expect(
      actionIds.length,
      `CLI_ACTION_IDS could not be read out of ${ACTION_IDS_MODULE} — the declaration moved ` +
        'or changed shape, so the addressing check below is inert',
    ).toBeGreaterThan(50);

    for (const { tool, name, wasAView, why } of RETIRED) {
      expect(why.length, `${tool}.${name} is retired with no stated reason`).toBeGreaterThan(40);

      const composite = TOOL_REGISTRY.find((entry) => entry.name === tool);
      expect(composite, `${tool} is not registered, so this row checks nothing`).toBeDefined();

      // 1. The registry — what `describe(actions)` and the CLI command tree
      //    are both projections of.
      expect(
        composite!.actions.map((action) => action.name),
        `${tool} still registers the retired action \`${name}\``,
      ).not.toContain(name);

      // 2. The tool-description advertisement. Nothing derives it from the
      //    registry, so it is the surface most likely to keep a dead name.
      expect(
        advertisedActions(composite!.slimDescription),
        `${tool}'s slimDescription still advertises \`${name}\``,
      ).not.toContain(name);

      // 3. The compiled addressing set. It is generated from the declarations,
      //    but by a SEPARATE gesture from editing them, so a retirement that
      //    never re-ran the generator ships a client that can still address a
      //    name the router answers `UNKNOWN_ACTION` for.
      expect(
        actionIds,
        `${ACTION_IDS_MODULE} still addresses \`${tool}.${name}\` — regenerate the ` +
          'compiled contract artifacts',
      ).not.toContain(`${tool}.${name}`);

      if (!wasAView) continue;

      // 4. The projection name space. A name left here reserves it against
      //    custom views while nothing serves it.
      expect(
        [...BUILTIN_VIEW_NAMES],
        `BUILTIN_VIEW_NAMES still reserves \`${name}\``,
      ).not.toContain(name);

      // 5. The `--follow` set. A member here gets a `--follow` flag registered
      //    on a subcommand that no longer exists.
      expect(
        followActions,
        `VIEW_FOLLOW_ACTIONS still lists \`${name}\` as a pollable view`,
      ).not.toContain(name);
    }
  });
});
